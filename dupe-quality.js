'use strict';
// Smart Quality Selection: which copy of a group to keep, and why.
//
// The biggest file is not automatically the best: a 4 MB JPEG re-saved from a
// 1 MB original adds bytes, not detail, and an H.264 file at twice the bitrate
// of an HEVC one may hold the same picture. The score weighs what the file
// shows (resolution, sharpness, codec-adjusted bitrate, full length, audio)
// over what it weighs, then prefers the copy something depends on (a library
// item, an app's post) and the original over an intended web rendition.
//
// Every rule returns a keeper and the reasons; the owner can always choose
// another copy.

const RULES = ['recommended', 'highest_quality', 'highest_resolution', 'largest', 'smallest', 'oldest', 'newest', 'keep_original', 'manual'];
const RULE_LABELS = {
  recommended: 'Recommended',
  highest_quality: 'Highest quality',
  highest_resolution: 'Highest resolution',
  largest: 'Largest file',
  smallest: 'Smallest file',
  oldest: 'Oldest',
  newest: 'Newest',
  keep_original: 'Keep original',
  manual: 'Manual selection',
};

// Bits per pixel per second a codec needs for the same picture, relative to
// H.264.
const CODEC_EFFICIENCY = { h264: 1, avc: 1, mpeg4: 0.7, mpeg2video: 0.5, hevc: 1.6, h265: 1.6, vp9: 1.5, av1: 1.9, vp8: 0.9 };
// Picture formats: lossless and modern lossy formats over old lossy ones.
// Only a tie-breaker: a PNG made from a JPEG is not better than the JPEG.
const IMAGE_FORMAT = { png: 3, tiff: 3, tif: 3, heic: 2, heif: 2, avif: 2, webp: 1, jpg: 1, jpeg: 1, mjpeg: 1, gif: 0, bmp: 0 };

const extOf = (rel) => ((/\.([a-z0-9]+)$/i.exec(rel) || [])[1] || '').toLowerCase();
const pixels = (m) => (m.width && m.height ? m.width * m.height : 0);

// m: { id, rel, bytes, mtime_ms, kind, width, height, duration, vcodec, acodec,
//      bitrate, sharpness, referenced (bool: an item or an app post uses it),
//      webOptimized, derivative, original (bool: known first download) }
function scoreMember(m, group) {
  const reasons = [];
  let s = 0;
  const maxPx = Math.max(...group.map(pixels), 0);
  if (maxPx && pixels(m)) {
    const rel = pixels(m) / maxPx;
    s += 40 * rel;
    if (rel === 1 && group.some((o) => pixels(o) && pixels(o) < maxPx)) reasons.push(`Highest resolution (${m.width}x${m.height})`);
    else if (rel < 0.9) reasons.push(`Lower resolution (${m.width}x${m.height})`);
  }
  if (m.kind === 'video') {
    const maxDur = Math.max(...group.map((o) => o.duration || 0));
    if (maxDur && m.duration && m.duration < maxDur * 0.97) {
      s -= 50;
      reasons.push(`Shorter than the others (${Math.round(m.duration)} s of ${Math.round(maxDur)} s)`);
    }
    const eff = (o) => (o.bitrate && pixels(o) ? (o.bitrate * (CODEC_EFFICIENCY[o.vcodec] || 1)) / pixels(o) : 0);
    const maxEff = Math.max(...group.map(eff), 0);
    if (maxEff && eff(m)) {
      s += 20 * (eff(m) / maxEff);
      if (eff(m) === maxEff && group.length > 1) reasons.push(`Most picture data for its codec (${m.vcodec || 'unknown'}, ${Math.round((m.bitrate || 0) / 1000)} kb/s)`);
    }
    if (m.acodec) s += 8;
    else if (group.some((o) => o.acodec)) reasons.push('No audio track');
  } else if (m.kind === 'image') {
    const sharp = Math.max(...group.map((o) => o.sharpness || 0), 0);
    if (sharp && m.sharpness) {
      s += 15 * (m.sharpness / sharp);
      if (m.sharpness === sharp && group.length > 1) reasons.push('Sharpest');
    }
    s += IMAGE_FORMAT[extOf(m.rel)] || 0;
  }
  if (m.referenced) { s += 12; reasons.push('In use by a library item or an app post'); }
  if (m.original) { s += 10; reasons.push('The original download'); }
  if (m.webOptimized) { s -= 15; reasons.push('A web-optimised rendition'); }
  if (m.derivative) { s -= 40; reasons.push('Generated by an app (thumbnail, poster or cache)'); }
  const oldest = Math.min(...group.map((o) => o.mtime_ms || Infinity));
  if (m.mtime_ms === oldest && group.length > 1) { s += 3; reasons.push('Oldest copy'); }
  return { score: Math.round(s * 10) / 10, reasons };
}

const by = (fn, dir = -1) => (a, b) => (fn(a) === fn(b) ? a.id - b.id : dir * (fn(a) - fn(b)));

// Picks the copy to keep under one rule. Returns { keepId, rule, reasons,
// scores: Map id -> { score, reasons } }.
function choose(members, rule = 'recommended', manualId = null) {
  const scores = new Map(members.map((m) => [m.id, scoreMember(m, members)]));
  const list = [...members];
  let pick;
  switch (rule) {
    case 'highest_resolution': pick = list.sort(by((m) => pixels(m) * 1e6 + scores.get(m.id).score))[0]; break;
    case 'largest': pick = list.sort(by((m) => m.bytes))[0]; break;
    case 'smallest': pick = list.sort(by((m) => m.bytes, 1))[0]; break;
    case 'oldest': pick = list.sort(by((m) => m.mtime_ms || 0, 1))[0]; break;
    case 'newest': pick = list.sort(by((m) => m.mtime_ms || 0))[0]; break;
    case 'keep_original': pick = list.sort(by((m) => (m.original ? 1e6 : 0) + (m.webOptimized || m.derivative ? -1e5 : 0) - (m.mtime_ms || 0) / 1e12))[0]; break;
    case 'manual': pick = list.find((m) => m.id === Number(manualId)) || null; break;
    case 'highest_quality':
    case 'recommended':
    default: pick = list.sort(by((m) => scores.get(m.id).score))[0];
  }
  return {
    keepId: pick ? pick.id : null,
    rule: RULES.includes(rule) ? rule : 'recommended',
    reasons: pick ? scores.get(pick.id).reasons : [],
    scores,
  };
}

module.exports = { choose, scoreMember, RULES, RULE_LABELS, CODEC_EFFICIENCY };
